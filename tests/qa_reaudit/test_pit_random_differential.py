"""Randomized differential PIT tests (QA track A).

For every seed a random company with a multi-year filing timeline (restatements,
withdrawals, late and early filings, duplicates, out-of-order ingestion, non-UTC
timestamp formats, 'USD millions' scaling, YTD/discrete/full quarterly styles)
is generated by tests/qa_reaudit/pit_oracle.py, ingested into the real store and
compared with an independent oracle at random probe instants (including exact
publication instants +-1 microsecond).

(PHASE 98 truncated-database identity lives in test_pit_phase98.py.)
"""
from __future__ import annotations
import json
import math
import random
from dataclasses import replace
from datetime import timedelta

import pytest

from tests.qa_reaudit import pit_oracle as O

from fundamentals.api import FundamentalAPI
from fundamentals.features import FundamentalFeatureEngine

SEEDS = list(range(320))


def close(a, b):
    if a is None or b is None:
        return a is None and b is None
    return math.isclose(a, b, rel_tol=1e-12, abs_tol=1e-9)


def check_snapshot(store, snap, company, T, tag):
    exp = O.snapshot_oracle(company.facts, T)
    assert snap['status'] == exp['status'], f'{tag}: status {snap["status"]} vs {exp["status"]}'
    # TTM
    t, et = snap['ttm'], exp['ttm']
    assert t['period_end'] == et['period_end'], f'{tag}: ttm period_end'
    assert t['period_start'] == et['period_start'], f'{tag}: ttm period_start'
    assert t['status'] == et['status'], f'{tag}: ttm status'
    assert t['reasons'] == et['reasons'], f'{tag}: ttm reasons {t["reasons"]} vs {et["reasons"]}'
    for m, v in et['values'].items():
        assert close(t['values'][m], v), f'{tag}: ttm {m}: {t["values"][m]} vs {v}'
    if exp['status'] == 'MISSING':
        assert snap['features'] == {}
        return exp
    assert snap['period_end'] == exp['period_end'], f'{tag}: period_end'
    assert snap['period_start'] == exp['period_start'], f'{tag}: period_start'
    assert snap['age_days'] == exp['age_days'], f'{tag}: age'
    assert snap['raw'] == exp['raw'], f'{tag}: raw current-period facts differ'
    for name, v in exp['features'].items():
        assert close(snap['features'][name], v), f'{tag}: feature {name}: {snap["features"][name]} vs {v}'
    # lineage: every id is the visible winner version at T
    win = O.visible_winners(company.facts, T)
    latest_av = None
    for i in snap['lineage']:
        row = store.db.execute('select metric,period_start,period_end,value,available_at from observations where id=?', (i,)).fetchone()
        assert row is not None, f'{tag}: lineage id missing'
        w = win[(row['metric'], row['period_start'], row['period_end'])]
        assert O.dt_utc(row['available_at']) == w.available, f'{tag}: lineage uses a non-winning vintage for {tuple(row)[:3]}'
        assert (row['value'] if row['value'] is not None else None) == w.value or close(row['value'], w.value)
        assert w.available <= T, f'{tag}: lineage row published after T'
        latest_av = max(latest_av, w.available) if latest_av else w.available
    assert O.dt_utc(snap['available_at']) == latest_av, f'{tag}: available_at is not max over lineage'
    assert O.dt_utc(snap['available_at']) <= T
    assert O.dt_utc(snap['reported_at']) <= O.dt_utc(snap['available_at'])
    return exp


@pytest.mark.parametrize('seed', SEEDS, ids=lambda s: f'seed{s}')
def test_snapshot_ttm_and_visibility_match_independent_oracle(seed):
    company = O.gen_company(seed)
    store = O.build_store(company.facts, company.symbol, company.scale_label, seed)
    engine = FundamentalFeatureEngine(store)
    rng = random.Random(seed ^ 0xBEEF)
    for n, T in enumerate(O.pick_times(rng, company.facts, 5)):
        tag = f'seed={seed} T#{n}={T.isoformat()}'
        T_in = O.render_ts(T, rng)
        # store.as_of visible set == oracle visible winners (value, instant and key)
        rows = store.as_of(company.symbol, T_in, kind='financial')
        win = O.visible_winners(company.facts, T)
        assert len(rows) == len(win), f'{tag}: visible row count {len(rows)} vs {len(win)}'
        for r in rows:
            w = win[(r['metric'], r['period_start'], r['period_end'])]
            assert O.dt_utc(r['available_at']) == w.available, f'{tag}: wrong vintage for {r["metric"]} {r["period_end"]}'
            assert close(r['value'], w.value), f'{tag}: value {r["value"]} vs {w.value}'
        snap = engine.snapshot(company.symbol, T_in)
        check_snapshot(store, snap, company, T, tag)
        if n == 0:  # API path must agree with the engine
            api = FundamentalAPI(store)
            via_api = api.get('/fundamentals/' + company.symbol, {'as_of': T.isoformat()})
            assert O.canon(via_api) == O.canon(engine.snapshot(company.symbol, T.isoformat())), f'{tag}: API != engine'
            ttm = api.get('/fundamentals/' + company.symbol + '/ttm', {'as_of': T.isoformat()})
            assert O.canon(ttm['values']) == O.canon(snap['ttm']['values']) or all(close(ttm['values'][k], snap['ttm']['values'][k]) for k in ttm['values'])


